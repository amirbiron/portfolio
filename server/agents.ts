/**
 * טוען את מסמך הידע של כל סוכן פעם אחת, בעליית השרת.
 * סוכן שהמסמך שלו לא נקרא לא נטען בכלל: בלי המסמך הוא היה עונה מהזיכרון
 * הכללי של המודל, כלומר ממציא פרטים על הפרויקט. הבקשות אליו נענות בשגיאה,
 * ושאר הסוכנים ממשיכים לעבוד.
 */
export function loadAgents(docsDir: string): Map<string, Agent> {
  const agents = new Map<string, Agent>();
  for (const [slug, spec] of Object.entries(AGENT_SPECS)) {
    const docPath = path.join(docsDir, spec.knowledgeFile);
    let knowledgeDoc: string;
    try {
      knowledgeDoc = fs.readFileSync(docPath, "utf-8");
    } catch (err) {
      console.error(
        `AI agent "${slug}" disabled: cannot read knowledge doc ${docPath}:`,
        err
      );
      continue;
    }
    if (!knowledgeDoc.trim()) {
      console.error(
        `AI agent "${slug}" disabled: knowledge doc ${docPath} is empty`
      );
      continue;
    }
    agents.set(slug, { slug, systemPrompt: spec.buildPrompt(knowledgeDoc) });
  }
  return agents;
}

/** כל הסוכנים שמוגדרים, כולל כאלה שלא נטענו — כדי להבדיל בין "לא קיים" ל"לא זמין" */
export function isKnownAgent(slug: string): boolean {
  return Object.prototype.hasOwnProperty.call(AGENT_SPECS, slug);
}
